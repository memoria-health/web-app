export interface CountryOption {
  code: string;
  name: string;
}

/**
 * Full country list as `{ code, name }`, sorted alphabetically by localized
 * name. `code` is the ISO alpha-2 wire value; `name` is the display label.
 * Falls back to the raw code if the runtime can't localize one.
 */
export function countryOptions(locale = 'en'): CountryOption[] {
  const display = new Intl.DisplayNames([locale], { type: 'region' });
  return ISO_ALPHA2.map((code) => ({
    code,
    name: display.of(code) ?? code,
  })).sort((a, b) => a.name.localeCompare(b.name, locale));
}

/** Localized display name for a single country code (for read-only display). */
export function countryName(code: string, locale = 'en'): string {
  try {
    return new Intl.DisplayNames([locale], { type: 'region' }).of(code) ?? code;
  } catch {
    return code;
  }
}
